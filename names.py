def fem_surname(s: str) -> str:
    if s.endswith("ий"):
        return s[:-2] + "ая"
    return s + "а"


def make_name(rng, female: bool) -> str:
    sur = str(rng.choice(SURN))
    patr = str(rng.choice(PATR_BASE))
    if female:
        return f"{fem_surname(sur)} {rng.choice(F_FIRST)} {patr}на"
    return f"{sur} {rng.choice(M_FIRST)} {patr}ич"


